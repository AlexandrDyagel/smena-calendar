/**
 * Производственный календарь России: фиксированные (непереносимые) праздники.
 * Хранятся в виде «MM-DD», поэтому применимы к любому году.
 * Переносы выходных в приложении сознательно не учитываются —
 * это настраиваемая эвристика, а не юридически точный календарь.
 */
export const RU_FIXED_HOLIDAYS: Record<string, string> = {
  '01-01': 'Новый год',
  '01-02': 'Новогодние каникулы',
  '01-03': 'Новогодние каникулы',
  '01-04': 'Новогодние каникулы',
  '01-05': 'Новогодние каникулы',
  '01-06': 'Новогодние каникулы',
  '01-07': 'Рождество Христово',
  '01-08': 'Новогодние каникулы',
  '02-23': 'День защитника Отечества',
  '03-08': 'Международный женский день',
  '05-01': 'Праздник Весны и Труда',
  '05-09': 'День Победы',
  '06-12': 'День России',
  '11-04': 'День народного единства',
}

/** Название праздника по дате «MM-DD» либо null. */
export function holidayName(monthDay: string): string | null {
  return RU_FIXED_HOLIDAYS[monthDay] ?? null
}

/** Список всех фиксированных праздников для интерфейса. */
export const HOLIDAY_LIST: Array<{ monthDay: string; name: string }> = Object.entries(
  RU_FIXED_HOLIDAYS,
).map(([monthDay, name]) => ({ monthDay, name }))
